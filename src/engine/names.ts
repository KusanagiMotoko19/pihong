export interface GeneratedName {
  name: string
  courtesy: string
}

export function makeName(rng: Rng): GeneratedName {
  const surname = rng.pick(SURNAMES)
  let given: string
  if (rng.chance(0.58)) {
    given = rng.pick(GIVEN)
  } else {
    given = rng.pick(DOUBLE_A) + rng.pick(DOUBLE_B)
  }
  const courtesy = rng.pick(ZI_FIRST) + rng.pick(ZI_SECOND)
  return { name: surname + given, courtesy }
}

export function makeOrigin(rng: Rng): string {
  return rng.pick(HOMETOWNS)
}

/** 科第：进士居多（堂官几乎全是进士），举贡次之 */
export function makeJinshi(rng: Rng, senior: boolean): string {
  const pool = senior ? JINSHI_YEARS.slice(0, 9) : JINSHI_YEARS
  const year = rng.pick(pool)
  const r = rng.next()
  if (r < 0.86) return `${year}进士`
  if (r < 0.95) return `${year}举人`
  return '岁贡'
}
